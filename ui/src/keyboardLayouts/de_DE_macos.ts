  row
    .replace(/^(\(?)Backquote(\)?) /, "$1IntlBackslash$2 ")
    .replace(/^ShiftLeft (\(?)KeyZ/, "ShiftLeft $1Backquote$2 $1KeyZ");
const macBottomRow = "ControlLeft AltLeft MetaLeft Space MetaRight AltRight";

